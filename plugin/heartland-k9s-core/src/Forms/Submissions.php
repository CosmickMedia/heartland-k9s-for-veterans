<?php
/**
 * Private `hk9_submission` post type: stored form submissions with a read-only
 * admin view, list-table columns, and a daily retention cron.
 *
 * Meta (all private):
 *   _hk9_form (string) · _hk9_fields (array of sanitized values) · _hk9_mail_sent (bool)
 *   _hk9_ip_hash (daily-salted hash; never the IP) · _hk9_source_post (int) · _hk9_submitted_gmt (Y-m-d H:i:s)
 *
 * @package HK9\Core
 */

declare(strict_types=1);

namespace HK9\Core\Forms;

defined( 'ABSPATH' ) || exit;

final class Submissions {

	public const POST_TYPE = 'hk9_submission';
	public const CRON_HOOK = 'hk9_submissions_retention';

	/** Primitive caps generated by capability_type [hk9_submission, hk9_submissions]. */
	private const CAPS = [
		'edit_hk9_submission',
		'read_hk9_submission',
		'delete_hk9_submission',
		'edit_hk9_submissions',
		'edit_others_hk9_submissions',
		'publish_hk9_submissions',
		'read_private_hk9_submissions',
		'delete_hk9_submissions',
		'delete_private_hk9_submissions',
		'delete_published_hk9_submissions',
		'delete_others_hk9_submissions',
		'edit_private_hk9_submissions',
		'edit_published_hk9_submissions',
		'hk9_view_submissions',
	];

	private static bool $writing = false;

	public static function register(): void {
		add_action( 'init', [ self::class, 'register_post_type' ], 5 );
		add_filter( 'hk9/post_types/definitions', [ self::class, 'definition_override' ] );
		add_action( 'init', [ self::class, 'ensure_cron' ], 20 );
		add_action( self::CRON_HOOK, [ self::class, 'run_retention' ] );
		add_filter( 'user_has_cap', [ self::class, 'grant_admin_caps' ], 10, 4 );
		add_filter( 'wp_insert_post_data', [ self::class, 'enforce_read_only' ], 10, 2 );
		add_filter( 'wp_untrash_post_status', [ self::class, 'untrash_status' ], 10, 2 );

		if ( is_admin() ) {
			add_action( 'admin_menu', [ self::class, 'fallback_menu' ], 9 );
			add_action( 'add_meta_boxes_' . self::POST_TYPE, [ self::class, 'meta_boxes' ] );
			add_action( 'admin_enqueue_scripts', [ self::class, 'enqueue_admin_assets' ] );
			add_filter( 'manage_' . self::POST_TYPE . '_posts_columns', [ self::class, 'columns' ] );
			add_action( 'manage_' . self::POST_TYPE . '_posts_custom_column', [ self::class, 'column_content' ], 10, 2 );
			add_filter( 'post_row_actions', [ self::class, 'row_actions' ], 10, 2 );
			add_filter( 'bulk_actions-edit-' . self::POST_TYPE, [ self::class, 'bulk_actions' ] );
			add_action( 'restrict_manage_posts', [ self::class, 'filter_dropdown' ] );
			add_action( 'pre_get_posts', [ self::class, 'apply_filter' ] );
			add_filter( 'enter_title_here', [ self::class, 'title_placeholder' ], 10, 2 );
			add_filter( 'post_updated_messages', [ self::class, 'updated_messages' ] );
		}
	}

	public static function activate(): void {
		self::register_post_type();
		self::ensure_cron();
	}

	public static function deactivate(): void {
		wp_clear_scheduled_hook( self::CRON_HOOK );
	}

	/**
	 * When PostTypes\Registrar registers the CPTs it runs first at the same priority;
	 * this filter layers the form-owned definition (labels, export/user-deletion guards)
	 * over its entry so the effective registration is identical either way.
	 *
	 * @param array<string,array> $types type => register_post_type() args.
	 */
	public static function definition_override( array $types ): array {
		if ( isset( $types[ self::POST_TYPE ] ) && is_array( $types[ self::POST_TYPE ] ) ) {
			$types[ self::POST_TYPE ] = array_merge( $types[ self::POST_TYPE ], self::post_type_args() );
		}
		return $types;
	}

	public static function register_post_type(): void {
		if ( post_type_exists( self::POST_TYPE ) ) {
			return;
		}
		register_post_type( self::POST_TYPE, self::post_type_args() );
	}

