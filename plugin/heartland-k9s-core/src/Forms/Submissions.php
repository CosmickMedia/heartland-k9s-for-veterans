				'edit_item'          => __( 'View Submission', 'heartland-k9s-core' ),
				'view_item'          => __( 'View Submission', 'heartland-k9s-core' ),
				'search_items'       => __( 'Search submissions', 'heartland-k9s-core' ),
				'not_found'          => __( 'No submissions yet.', 'heartland-k9s-core' ),
				'not_found_in_trash' => __( 'No submissions in Trash.', 'heartland-k9s-core' ),
			],
			'description'         => __( 'Messages received through the contact and application inquiry forms.', 'heartland-k9s-core' ),
			'public'              => false,
			'publicly_queryable'  => false,
