	/** Minimal "Heartland" top-level menu when the Admin\Menu module is absent (dev safety net). */
	public static function fallback_menu(): void {
		if ( class_exists( 'HK9\\Core\\Admin\\Menu' ) ) {
			return;
		}
		global $admin_page_hooks;
		if ( isset( $admin_page_hooks['hk9'] ) ) {
			return;
		}
		add_menu_page( __( 'Heartland', 'heartland-k9s-core' ), __( 'Heartland', 'heartland-k9s-core' ), 'edit_hk9_submissions', 'hk9', [ self::class, 'fallback_page' ], 'dashicons-pets', 25 );
	}

	public static function fallback_page(): void {
		echo '<div class="wrap"><h1>' . esc_html__( 'Heartland', 'heartland-k9s-core' ) . '</h1><p><a href="' . esc_url( admin_url( 'edit.php?post_type=' . self::POST_TYPE ) ) . '">' . esc_html__( 'Form Submissions', 'heartland-k9s-core' ) . '</a></p></div>';
	}

	public static function enqueue_admin_assets( string $hook ): void {
		$screen = function_exists( 'get_current_screen' ) ? get_current_screen() : null;
		if ( ! $screen || self::POST_TYPE !== $screen->post_type ) {
			return;
		}
		wp_enqueue_style( 'hk9-forms-admin', HK9_CORE_URL . 'assets/css/forms-admin.css', [], HK9_CORE_VERSION );
	}

	public static function meta_boxes( \WP_Post $post ): void {
		remove_meta_box( 'slugdiv', self::POST_TYPE, 'normal' );
		add_meta_box( 'hk9_submission_detail', __( 'Submission', 'heartland-k9s-core' ), [ self::class, 'render_detail' ], self::POST_TYPE, 'normal', 'high' );
		add_meta_box( 'hk9_submission_delivery', __( 'Delivery', 'heartland-k9s-core' ), [ self::class, 'render_delivery' ], self::POST_TYPE, 'side', 'high' );
	}

	/** Read-only field table (every value escaped; nothing editable). */
	public static function render_detail( \WP_Post $post ): void {
		$form_id = (string) get_post_meta( $post->ID, '_hk9_form', true );
		$form    = Handler::form( $form_id );
		$fields  = get_post_meta( $post->ID, '_hk9_fields', true );
		$fields  = is_array( $fields ) ? $fields : [];

		echo '<p class="hk9-submission__note">' . esc_html__( 'Submissions are read-only. Use Trash to remove this record.', 'heartland-k9s-core' ) . '</p>';
		echo '<table class="hk9-submission__table widefat striped"><tbody>';
		$definitions = $form ? $form->fields() : [];
		$keys        = array_unique( array_merge( array_keys( $definitions ), array_keys( $fields ) ) );
		foreach ( $keys as $key ) {
			if ( ! array_key_exists( $key, $fields ) ) {
				continue;
			}
			$label = (string) ( $definitions[ $key ]['label'] ?? $key );
			$value = $form ? $form->display_value( (string) $key, $fields[ $key ] ) : ( is_scalar( $fields[ $key ] ) ? (string) $fields[ $key ] : '' );
			$multi = 'textarea' === ( $definitions[ $key ]['type'] ?? '' );
			echo '<tr><th scope="row">' . esc_html( $label ) . '</th><td' . ( $multi ? ' class="hk9-submission__multiline"' : '' ) . '>';
			if ( 'email' === ( $definitions[ $key ]['type'] ?? '' ) && is_email( $value ) ) {
				echo '<a href="' . esc_url( 'mailto:' . $value ) . '">' . esc_html( $value ) . '</a>';
			} else {
				echo '' !== $value ? esc_html( $value ) : '&mdash;';
			}
			echo '</td></tr>';
		}
		echo '</tbody></table>';
	}

	public static function render_delivery( \WP_Post $post ): void {
		$form_id   = (string) get_post_meta( $post->ID, '_hk9_form', true );
		$form      = Handler::form( $form_id );
		$sent      = (bool) get_post_meta( $post->ID, '_hk9_mail_sent', true );
		$source    = (int) get_post_meta( $post->ID, '_hk9_source_post', true );
		$submitted = (string) get_post_meta( $post->ID, '_hk9_submitted_gmt', true );
		$ip_hash   = (string) get_post_meta( $post->ID, '_hk9_ip_hash', true );

		echo '<dl class="hk9-submission__meta">';
		echo '<dt>' . esc_html__( 'Form', 'heartland-k9s-core' ) . '</dt><dd>' . esc_html( $form ? $form->label() : $form_id ) . '</dd>';
		echo '<dt>' . esc_html__( 'Submitted', 'heartland-k9s-core' ) . '</dt><dd>' . esc_html( '' !== $submitted ? get_date_from_gmt( $submitted, get_option( 'date_format' ) . ' ' . get_option( 'time_format' ) ) : '' ) . '</dd>';
		echo '<dt>' . esc_html__( 'Email notification', 'heartland-k9s-core' ) . '</dt><dd>' . self::mail_badge( $sent ) . '</dd>'; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- escaped in helper.
		if ( $form ) {
			echo '<dt>' . esc_html__( 'Recipients', 'heartland-k9s-core' ) . '</dt><dd>' . esc_html( implode( ', ', $form->recipients() ) ) . '</dd>';
		}
		if ( $source > 0 ) {
			echo '<dt>' . esc_html__( 'Source page', 'heartland-k9s-core' ) . '</dt><dd><a href="' . esc_url( (string) get_permalink( $source ) ) . '">' . esc_html( get_the_title( $source ) ) . '</a></dd>';
		}
		echo '<dt>' . esc_html__( 'Sender hash', 'heartland-k9s-core' ) . '</dt><dd><code>' . esc_html( '' !== $ip_hash ? substr( $ip_hash, 0, 12 ) : '—' ) . '</code></dd>';
		echo '</dl>';
		echo '<p class="hk9-submission__actions"><a class="button-link-delete" href="' . esc_url( (string) get_delete_post_link( $post->ID ) ) . '">' . esc_html__( 'Move to Trash', 'heartland-k9s-core' ) . '</a></p>';
	}

	private static function mail_badge( bool $sent ): string {
		return $sent
			? '<span class="hk9-badge hk9-badge--ok"><span class="dashicons dashicons-yes" aria-hidden="true"></span> ' . esc_html__( 'Sent', 'heartland-k9s-core' ) . '</span>'
			: '<span class="hk9-badge hk9-badge--fail"><span class="dashicons dashicons-warning" aria-hidden="true"></span> ' . esc_html__( 'Not sent', 'heartland-k9s-core' ) . '</span>';
	}

	public static function columns( array $columns ): array {
		return [
			'cb'        => $columns['cb'] ?? '<input type="checkbox" />',
			'title'     => __( 'Submission', 'heartland-k9s-core' ),
			'hk9_form'  => __( 'Form', 'heartland-k9s-core' ),
			'hk9_name'  => __( 'Name', 'heartland-k9s-core' ),
			'hk9_email' => __( 'Email', 'heartland-k9s-core' ),
			'date'      => __( 'Date', 'heartland-k9s-core' ),
			'hk9_mail'  => __( 'Mail sent', 'heartland-k9s-core' ),
		];
	}

	public static function column_content( string $column, int $post_id ): void {
		switch ( $column ) {
			case 'hk9_form':
				$form = Handler::form( (string) get_post_meta( $post_id, '_hk9_form', true ) );
				echo esc_html( $form ? $form->label() : (string) get_post_meta( $post_id, '_hk9_form', true ) );
				break;
			case 'hk9_name':
			case 'hk9_email':
				$fields = get_post_meta( $post_id, '_hk9_fields', true );
				$fields = is_array( $fields ) ? $fields : [];
				if ( 'hk9_name' === $column ) {
					echo esc_html( trim( (string) ( $fields['first_name'] ?? '' ) . ' ' . (string) ( $fields['last_name'] ?? '' ) ) );
				} else {
					$email = (string) ( $fields['email'] ?? '' );
					echo is_email( $email ) ? '<a href="' . esc_url( 'mailto:' . $email ) . '">' . esc_html( $email ) . '</a>' : esc_html( $email );
				}
				break;
			case 'hk9_mail':
				echo self::mail_badge( (bool) get_post_meta( $post_id, '_hk9_mail_sent', true ) ); // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- escaped in helper.
				break;
		}
	}

	public static function row_actions( array $actions, \WP_Post $post ): array {
		if ( self::POST_TYPE !== $post->post_type ) {
			return $actions;
		}
		unset( $actions['inline hide-if-no-js'], $actions['view'] );
		if ( isset( $actions['edit'] ) ) {
			$actions['edit'] = '<a href="' . esc_url( (string) get_edit_post_link( $post->ID ) ) . '">' . esc_html__( 'View', 'heartland-k9s-core' ) . '</a>';
		}
		return $actions;
	}

	public static function bulk_actions( array $actions ): array {
		unset( $actions['edit'] );
		return $actions;
	}

	public static function filter_dropdown( string $post_type ): void {
		if ( self::POST_TYPE !== $post_type ) {
			return;
		}
		$current = isset( $_GET['hk9_form'] ) ? sanitize_key( wp_unslash( $_GET['hk9_form'] ) ) : ''; // phpcs:ignore WordPress.Security.NonceVerification.Recommended -- read-only list filter.
		echo '<label class="screen-reader-text" for="hk9-filter-form">' . esc_html__( 'Filter by form', 'heartland-k9s-core' ) . '</label>';
		echo '<select name="hk9_form" id="hk9-filter-form">';
		echo '<option value="">' . esc_html__( 'All forms', 'heartland-k9s-core' ) . '</option>';
		foreach ( Handler::forms() as $id => $form ) {
			echo '<option value="' . esc_attr( $id ) . '"' . selected( $current, $id, false ) . '>' . esc_html( $form->label() ) . '</option>';
		}
		echo '</select>';
	}

	public static function apply_filter( \WP_Query $query ): void {
		if ( ! is_admin() || ! $query->is_main_query() || self::POST_TYPE !== $query->get( 'post_type' ) ) {
			return;
		}
		$form = isset( $_GET['hk9_form'] ) ? sanitize_key( wp_unslash( $_GET['hk9_form'] ) ) : ''; // phpcs:ignore WordPress.Security.NonceVerification.Recommended -- read-only list filter.
		if ( '' !== $form && Handler::form( $form ) ) {
			$query->set(
				'meta_query',
				[
					[
						'key'   => '_hk9_form',
						'value' => $form,
					],
				]
			);
		}
	}

	public static function title_placeholder( string $placeholder, \WP_Post $post ): string {
		return self::POST_TYPE === $post->post_type ? '' : $placeholder;
	}

	public static function updated_messages( array $messages ): array {
		$messages[ self::POST_TYPE ] = array_fill( 0, 11, __( 'Submissions are read-only.', 'heartland-k9s-core' ) );
		return $messages;
	}
}
