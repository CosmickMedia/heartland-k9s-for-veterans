	/** Administrators can always manage submissions, regardless of stored role caps. */
	public static function grant_admin_caps( array $allcaps, array $caps, array $args, \WP_User $user ): array {
		if ( empty( $allcaps['manage_options'] ) ) {
			return $allcaps;
		}
		foreach ( self::CAPS as $cap ) {
			$allcaps[ $cap ] = true;
		}
		return $allcaps;
	}

	/**
	 * Store a validated submission.
	 *
	 * @param array<string,mixed> $values  Validated values.
	 * @param array<string,mixed> $context {ip_hash, source_post, submitted_gmt}
	 * @return int Post id (0 on failure).
	 */
	public static function store( AbstractForm $form, array $values, array $context = [] ): int {
		$submitted_gmt = (string) ( $context['submitted_gmt'] ?? current_time( 'mysql', true ) );
		$title         = sprintf(
			/* translators: 1: form label, 2: date/time */
			__( '%1$s — %2$s', 'heartland-k9s-core' ),
			$form->label(),
			wp_date( get_option( 'date_format' ) . ' ' . get_option( 'time_format' ), strtotime( $submitted_gmt . ' UTC' ) ?: null )
		);
		// Searchable summary (name + email) so the admin search box finds submissions; never rendered publicly.
		$content = trim( $form->submitter_name( $values ) . ' ' . $form->submitter_email( $values ) );

		self::$writing = true;
		$id            = wp_insert_post(
			[
				'post_type'     => self::POST_TYPE,
				'post_status'   => 'publish',
				'post_title'    => $title,
				'post_content'  => $content,
				'post_author'   => 0,
				'post_date_gmt' => $submitted_gmt,
				'post_date'     => get_date_from_gmt( $submitted_gmt ),
				'meta_input'    => [
					'_hk9_form'          => $form->id(),
					'_hk9_fields'        => $values,
					'_hk9_mail_sent'     => 0,
					'_hk9_ip_hash'       => (string) ( $context['ip_hash'] ?? '' ),
					'_hk9_source_post'   => (int) ( $context['source_post'] ?? 0 ),
					'_hk9_submitted_gmt' => $submitted_gmt,
				],
			],
			false
		);
		self::$writing = false;

		return is_int( $id ) && $id > 0 ? $id : 0;
	}

	public static function record_mail( int $submission_id, bool $sent ): void {
		if ( $submission_id > 0 ) {
			update_post_meta( $submission_id, '_hk9_mail_sent', $sent ? 1 : 0 );
		}
	}

	/** Restored submissions go back to 'publish' (core would demote them to 'draft'). */
	public static function untrash_status( string $new_status, int $post_id ): string {
		return self::POST_TYPE === get_post_type( $post_id ) ? 'publish' : $new_status;
	}

	/** Prevent edits from the admin UI: only trash/untrash transitions may change a stored submission. */
	public static function enforce_read_only( array $data, array $postarr ): array {
		if ( self::$writing || self::POST_TYPE !== ( $data['post_type'] ?? '' ) ) {
			return $data;
		}
		$id = (int) ( $postarr['ID'] ?? 0 );
		if ( 0 === $id ) {
			return $data;
		}
		$current = get_post( $id );
		if ( ! $current instanceof \WP_Post ) {
			return $data;
		}
		$trashing   = 'trash' === ( $data['post_status'] ?? '' );
		$untrashing = 'trash' === $current->post_status;
		foreach ( [ 'post_title', 'post_content', 'post_excerpt', 'post_name', 'post_author', 'post_date', 'post_date_gmt', 'post_parent', 'menu_order' ] as $field ) {
			$data[ $field ] = $current->$field;
		}
		if ( ! $trashing && ! $untrashing ) {
			$data['post_status'] = $current->post_status;
		}
		return $data;
	}

	/* ---------------------------------------------------------------------
	 * Retention
	 * ------------------------------------------------------------------ */

	public static function ensure_cron(): void {
		if ( ! wp_next_scheduled( self::CRON_HOOK ) ) {
			wp_schedule_event( time() + HOUR_IN_SECONDS, 'daily', self::CRON_HOOK );
		}
	}

	/** Delete submissions older than `forms.retention_days` (0 = keep forever). Batched. */
	public static function run_retention(): int {
		$days = Config::retention_days();
		if ( $days <= 0 ) {
			return 0;
		}
		$before  = gmdate( 'Y-m-d H:i:s', time() - $days * DAY_IN_SECONDS );
		$deleted = 0;
		for ( $batch = 0; $batch < 20; $batch++ ) {
			$ids = get_posts(
				[
					'post_type'              => self::POST_TYPE,
					'post_status'            => 'any',
					'fields'                 => 'ids',
					'numberposts'            => 100,
					'no_found_rows'          => true,
					'update_post_meta_cache' => false,
					'update_post_term_cache' => false,
					'date_query'             => [
						[
							'column' => 'post_date_gmt',
							'before' => $before,
						],
					],
				]
			);
			if ( [] === $ids ) {
				break;
			}
			foreach ( $ids as $id ) {
				if ( wp_delete_post( (int) $id, true ) ) {
					$deleted++;
				}
			}
		}
		return $deleted;
	}

